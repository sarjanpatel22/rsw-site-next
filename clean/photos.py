"""Writes photos.js: small copies of the pictures the particles draw, as data URLs. python3 photos.py
A picture only becomes particles if the page may read its pixels, and a page opened as a file may not read even its own
images; a data URL it may. They're small anyway: the particles only need about 160 x 200 pixels of a picture.
Run it again after changing which pictures the scenes use (their data-photo / data-photo-manga in index.html)."""
import base64
import json
import pathlib
import re
import subprocess
import tempfile

here = pathlib.Path(__file__).resolve().parent
html = (here / "index.html").read_text()
sources = sorted(set(re.findall(r'data-photo(?:-manga)?="([^"]+)"', html)))
photos = {}
with tempfile.TemporaryDirectory() as tmp:
    for src in sources:
        out = pathlib.Path(tmp) / "small.webp"
        subprocess.run(["convert", str((here / src).resolve()), "-resize", "220x220>", "-quality", "82", str(out)], check=True)
        photos[src] = "data:image/webp;base64," + base64.b64encode(out.read_bytes()).decode()
        print(f"{src}: {out.stat().st_size // 1024} KB")
(here / "photos.js").write_text(
    "// Generated by photos.py: small copies of the pictures the particles draw, as data URLs, which a page opened as a\n"
    "// file may still read (it can't read its own image files). Don't edit by hand.\n"
    f"window.RSW_PHOTOS = {json.dumps(photos, indent=0)};\n"
)
print(f"photos.js: {(here / 'photos.js').stat().st_size // 1024} KB, {len(photos)} pictures")
